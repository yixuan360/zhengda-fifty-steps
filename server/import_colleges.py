created = 0
updated = 0
for name, lat, lng, radius, summary, desc in all_items:
    obj, is_new = Spot.objects.get_or_create(
        name=name,
        defaults={'lat': lat, 'lng': lng, 'trigger_radius': radius,
                  'summary': summary, 'description': desc, 'is_active': True},
    )
    if is_new:
        created += 1
    else:
        obj.lat = lat; obj.lng = lng; obj.trigger_radius = radius
        obj.summary = summary; obj.description = desc
        obj.save()
        updated += 1

