def ensure_category():
    cat, created = Category.objects.update_or_create(
        key=CATEGORY_KEY,
        defaults={'label': CATEGORY_LABEL, 'color': CATEGORY_COLOR, 'sort_order': 10},
    )
    status = '新建' if created else '已存在并更新'
    print(f'分类“{CATEGORY_LABEL}”({CATEGORY_KEY})：{status}')
    return cat


def rename_typo():
    """将旧数据中的错别字“天建大道”重命名为“天健大道”，避免重复创建。"""
    renamed = Spot.objects.filter(name='天建大道').update(name='天健大道')
    if renamed:
        print(f'发现并重命名 {renamed} 个错别字景点：天建大道 → 天健大道')


def import_all():
    rename_typo()
    cat = ensure_category()
    created = 0
    updated = 0

    for item in ROADS_AND_BRIDGES:
        defaults = {
            'lat': item['lat'],
            'lng': item['lng'],
            'category': cat.key,
            'trigger_radius': item['radius'],
            'summary': item['summary'],
            'description': item['desc'],
            'is_active': True,
        }
        obj, is_new = Spot.objects.update_or_create(
            name=item['name'],
            defaults=defaults,
        )
        if is_new:
            created += 1
        else:
            updated += 1
        print(f'  {"[NEW]" if is_new else "[UPD]"} #{obj.id} {obj.name} ({obj.lat}, {obj.lng})')

    total = Spot.objects.filter(category=cat.key).count()
    print(f'\n{"="*50}')
    print(f'导入完成：新增 {created}，更新 {updated}，分类“{CATEGORY_LABEL}”下共 {total} 个景点')
    print(f'{"="*50}')


if __name__ == '__main__':
    import_all()
