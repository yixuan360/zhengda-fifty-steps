def import_all():
    created = 0
    updated = 0
    for s in SPOTS:
        obj, is_new = Spot.objects.update_or_create(
            id=s['id'],
            defaults={
                'name': s['name'],
                'lat': s['lat'],
                'lng': s['lng'],
                'trigger_radius': s['radius'],
                'summary': s['summary'],
                'description': s['desc'],
                'is_active': True,
            },
        )
        if is_new:
            created += 1
        else:
            updated += 1
        print(f'  {"[NEW]" if is_new else "[UPD]"} #{s["id"]} {s["name"]} ({s["lat"]}, {s["lng"]})')

    total = Spot.objects.count()
    print(f'\n{"="*50}')
    print(f'导入完成：新增 {created}，更新 {updated}，数据库总计 {total} 个景点')
    print(f'{"="*50}')

