# ── 运行 ─────────────────────────────────────────────────

def seed():
    created = 0
    existed = 0
    for spot_data in SPOTS:
        obj, is_new = Spot.objects.update_or_create(
            name=spot_data['name'],
            defaults=spot_data,
        )
        if is_new:
            created += 1
            print(f'  [NEW] 新增：{obj.name}')
        else:
            existed += 1
            print(f'  [UPDATED] 更新：{obj.name}')

    total = Spot.objects.count()
    print(f'\n=== 景点种子数据完成：新增 {created}，已存在 {existed}，总计 {total} 个景点 ===')


if __name__ == '__main__':
    seed()
